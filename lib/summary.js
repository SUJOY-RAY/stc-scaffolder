/** Generate the STC-SUMMARY.md content for a bootstrapped project. */
function buildSummary({
  projectName,
  groupId,
  artifactId,
  version,
  javaVersion,
  springBootVersion,
  packageName,
  mainClass,
  dbName,
  dbHost,
  dbPort,
  dbUser,
  artifactUs,
  fields,
  javaType,
}) {
  const fieldList = fields.length
    ? fields.map((f) => `- \`${f.name}\` (\`${javaType(f.type)}\`)`).join('\n')
    : '(none)';

  return `
# ${projectName}

Generated by the STC Java Bootstrapper (reference: Spring Boot Java template).

## What was generated
- Maven project: groupId=\`${groupId}\`, artifactId=\`${artifactId}\`, version=\`${version}\`
- Java ${javaVersion}, Spring Boot ${springBootVersion}
- Package: \`${packageName}\`
- Main class: \`${mainClass}\`
- Database: MySQL (\`${dbName}\` at ${dbHost}:${dbPort}, user \`${dbUser}\`)
- Active profile: \`dev-mysql\` (MySQL only)

## Custom entity fields added to the User entity
${fieldList}

> Custom fields are persisted on the \`User\` entity. Wire them into
> \`SignupRequest\` and \`AuthService.signup(...)\` if you want them settable at registration.

## Auto-generated CRUD for User entity
- \`POST /api/users\`        → create
- \`GET /api/users\`         → list all
- \`GET /api/users/{id}\`    → get by id
- \`PUT /api/users/{id}\`    → update
- \`DELETE /api/users/{id}\` → delete

Files: \`controller/UserController.java\`, \`service/UserService.java\`,
\`dto/UserRequest.java\`, \`dto/UserResponse.java\`

## Project layout
\`\`\`
${projectName}/
├── pom.xml
├── mvnw / mvnw.cmd
├── src/main/resources/application.properties
├── src/main/resources/application-dev-mysql.properties   (MySQL dev)
└── src/main/java/${groupId.replace(/\./g, '/')}/${artifactId.replace(/-/g, '_')}/
    ├── ${mainClass}.java
    ├── controller/AuthController.java
    ├── security/...
    ├── service/AuthService.java
    ├── model/User.java          (includes your custom fields)
    ├── model/Role.java, ERole.java
    ├── repository/UserRepository.java, RoleRepository.java
    ├── dto/LoginRequest, SignupRequest, JwtResponse, MessageResponse
    └── bootstrap/DataInitializer.java
\`\`\`

## Run
1. Create the MySQL database:
   \`\`\`sql
   CREATE DATABASE ${dbName};
   \`\`\`
2. (Optional) edit \`src/main/resources/application-dev-mysql.properties\` credentials.
3. Run with the MySQL profile:
   \`\`\`bash
   ./mvnw spring-boot:run --spring.profiles.active=dev-mysql
   \`\`\`
   (Windows: \`mvnw.cmd spring-boot:run --spring.profiles.active=dev-mysql\`)

## Endpoints
- POST /api/auth/signin   → login, returns JWT
- POST /api/auth/signup   → register a user
- Protected endpoints require \`Authorization: Bearer <token>\`

Default seed (startup): username \`admin\`, password \`admin123\`, email \`admin@${artifactUs}.com\`.

> Change the JWT secret and default password before production.
`;
}

module.exports = { buildSummary };
